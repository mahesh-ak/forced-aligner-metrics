"""Exact regression: CTCAligner vs external reference alignments (MFA, DORECO).

Aligns held-out speech with this package's ``CTCAligner`` and compares the
resulting intervals against reference alignments produced by *other* tools -
never against alignments generated by this package itself:

* FLEURS ``de_de`` test split (streamed like ``test_metrics.py``) vs the
  Montreal Forced Aligner TextGrids in ``tests/data/alignments/mfa/de_de``,
  using ``mahesh27/mms-300m-ipa-fleurs`` + the ``de_de`` adapter;
* DORECO ``anal1239`` validation parquet in
  ``tests/data/alignments/doreco/anal1239/validation.parquet`` (audio + words
  + phones columns), using ``mahesh27/mms-300m-xsampa-doreco`` + the
  ``anal1239`` adapter.

The reference transcript is read from the reference alignment itself: the
phone labels grouped by the word spans form the aligner input (one
whitespace-separated entry per reference word) and the reference word labels
are passed as ``word_texts``. Reference phone labels in ``IGNORED_REF_LABELS``
(``spn`` = spoken noise in MFA) are ignored, and reference words left without
any phones are dropped from both the input and the expected word sequence.

Comparison rules - no heuristics:

* phones: the symbol sequence must match exactly, at the model tokenizer's
  own granularity (``processor.tokenizer`` per word - multi-character vocab
  symbols such as affricates stay single symbols on both sides). The only
  excused difference: where the tokenizer maps a symbol to ``<unk>``, the
  aligner emits ``<unk>`` where the reference has that symbol;
* words: the word sequence (count and texts) must match exactly.

Timestamps are NOT scored against the MFA TextGrids - those references
disagree with the audio on a large share of the FLEURS items (measured mean
AAS 499/442 ms word/phone), so only the symbol sequences are checked there.
Timestamps are scored only for DORECO (clean references), in aggregate with
the package's :func:`compute_aas` (absolute boundary deviation; same
interval-dict format as the other metrics) - the mean AAS over the compared
items must stay below 60 ms (measured ~59/39 ms word/phone). The MFA-based
evaluation with timing metrics remains in ``test_metrics.py``.

``MFA_REF_ITEMS=<n>`` / ``DORECO_REF_ITEMS=<n>`` limit the number of compared
items (``FAM_REF_ITEMS`` is accepted as an alias for ``MFA_REF_ITEMS``).
"""

import os

import pytest
import torch

from forced_aligner_metrics import CTCAligner, compute_aas

TEST_DATA_ROOT = os.path.join("tests", "data")
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
BATCH_SIZE = int(os.environ.get("FAM_BATCH_SIZE", "10"))
# reference phone labels ignored on the reference side (MFA spoken noise)
IGNORED_REF_LABELS = {"spn"}
# mean AAS bound over the compared DORECO items (ms) - timestamps are scored
# only on DORECO, whose references are clean (measured ~59/39 ms word/phone)
DORECO_MEAN_AAS_MAX_MS = 60.0

FLEURS_MODEL = "mahesh27/mms-300m-ipa-fleurs"
FLEURS_LANG = "de_de"
MFA_TG_DIR = os.path.join(TEST_DATA_ROOT, "alignments", "mfa", FLEURS_LANG)

DORECO_MODEL = "mahesh27/mms-300m-xsampa-doreco"
DORECO_LANG = "anal1239"
DORECO_PARQUET = os.path.join(TEST_DATA_ROOT, "alignments", "doreco", DORECO_LANG, "validation.parquet")


def _env_int(*names):
    for n in names:
        v = os.environ.get(n)
        if v:
            return int(v)
    return None


# --------------------------------------------------------------------------
# TextGrid reading (short and long oTextFile formats)
# --------------------------------------------------------------------------

def parse_textgrid(path):
    """Minimal oTextFile IntervalTier reader -> {tier: [(start, end, text)]}."""
    lines = open(path).read().splitlines()
    tiers = {}
    i, n = 0, len(lines)
    while i < n:
        s = lines[i].strip()
        if s in ('"IntervalTier"', 'class = "IntervalTier"'):
            long_fmt = s.startswith("class")
            name_line = lines[i + 1].strip()
            name = (
                name_line.split("=", 1)[1].strip().strip('"')
                if long_fmt
                else name_line.strip('"')
            )
            size_line = lines[i + 4].strip()
            count = int(size_line.split("=")[-1]) if long_fmt else int(size_line)
            entries = []
            j = i + 5
            for _ in range(count):
                if long_fmt:
                    # intervals [k]: / xmin = .. / xmax = .. / text = ".."
                    start = float(lines[j + 1].split("=")[1])
                    end = float(lines[j + 2].split("=")[1])
                    text = lines[j + 3].split("=", 1)[1].strip().strip('"')
                    entries.append((start, end, text))
                    j += 4
                else:
                    entries.append(
                        (float(lines[j]), float(lines[j + 1]), lines[j + 2].strip().strip('"'))
                    )
                    j += 3
            tiers[name] = entries
            i = j
        else:
            i += 1
    return tiers


# --------------------------------------------------------------------------
# Reference normalization + comparison
# --------------------------------------------------------------------------

def build_reference(words, phones, ignore=IGNORED_REF_LABELS):
    """Normalize a reference alignment into aligner input + expected tiers.

    ``words``/``phones`` are lists of ``(start, end, label)``. Phone labels
    are grouped by the word spans (interval midpoint inside the word); empty
    labels and labels in ``ignore`` are dropped, and words left without
    phones are dropped too (from both the input text and the expected words).

    Returns ``{"text", "word_text", "words", "per_word"}`` where ``per_word``
    is one list of ``(label, start, end)`` per kept word.
    """
    words = [w for w in words if w[2].strip() != ""]
    phones = [p for p in phones if p[2].strip() != "" and p[2] not in ignore]
    kept_words, per_word = [], []
    for w in words:
        grp = [p for p in phones if w[0] - 1e-9 <= (p[0] + p[1]) / 2 <= w[1] + 1e-9]
        if grp:
            kept_words.append(w)
            per_word.append([(p[2], p[0], p[1]) for p in grp])
    text = " ".join("".join(lab for lab, _, _ in grp) for grp in per_word)
    word_text = " ".join(w[2] for w in kept_words)
    return {"text": text, "word_text": word_text, "words": kept_words, "per_word": per_word}


def _word_tokens(aligner, word):
    """The aligner's token strings for one word (no word delimiter)."""
    tok = aligner.processor.tokenizer
    ids = aligner._tokenize_utterance(word)
    toks = tok.convert_ids_to_tokens(ids)
    delim_id = aligner._word_delimiter_id
    return [t for i, t in zip(ids, toks) if i != delim_id]


def _ref_token_entries(aligner, per_word, unk):
    """Reference phone labels re-segmented to tokenizer symbols.

    Returns a flat list of ``(start, end, token)`` aligned with the aligner's
    token sequence of the input text (each token gets the span of the
    reference label it belongs to).
    """
    entries = []
    for grp in per_word:
        wtoks = _word_tokens(aligner, "".join(lab for lab, _, _ in grp))
        ti = 0
        for lab, ps, pe in grp:
            need = len(lab)
            while need > 0 and ti < len(wtoks):
                t = wtoks[ti]
                ti += 1
                entries.append((ps, pe, t))
                need -= 1 if t == unk else len(t)
    return entries


def compare_against_reference(name, result, ref, aligner, with_aas=False):
    """Exact sequence comparison of one alignment result against a reference.

    Word and phone symbol sequences must match exactly (``<unk>`` excused on
    the aligner side where the tokenizer cannot represent a reference
    symbol). With ``with_aas=True`` the timestamps are additionally scored
    with the package's :func:`compute_aas`; returns
    ``(word_aas_ms, phone_aas_ms)`` (``(None, None)`` when ``with_aas`` is
    false).
    """
    iv = result.intervals()
    tok = aligner.processor.tokenizer
    unk = tok.unk_token or "<unk>"

    # words tier: exact word sequence (count + texts)
    ours_w = [e for e in iv["words"] if e["text"] != ""]
    ref_w = ref["words"]
    assert len(ours_w) == len(ref_w), (
        f"{name} words: {len(ref_w)} reference vs {len(ours_w)} aligned intervals"
    )
    for (rs, re_, rt), o in zip(ref_w, ours_w):
        assert o["text"] == rt, f"{name} words: {o['text']!r} vs {rt!r}"

    # phones tier: exact symbol sequence at the tokenizer's granularity
    ref_tok = _ref_token_entries(aligner, ref["per_word"], unk)
    expected = [t for _, _, t in ref_tok]
    ours_p = [e for e in iv["phones"] if e["text"] != ""]
    assert len(ours_p) == len(expected), (
        f"{name} phones: {len(expected)} reference vs {len(ours_p)} aligned tokens"
    )
    for (rs, re_, et), o in zip(ref_tok, ours_p):
        assert o["text"] == et or o["text"] == unk, (
            f"{name} phones: {o['text']!r} vs {et!r}"
        )
    # each word's aligned tokens must spell the raw reference labels exactly
    # (excused only where the tokenizer maps a symbol to <unk>)
    pos = 0
    for grp in ref["per_word"]:
        ref_str = "".join(lab for lab, _, _ in grp)
        wtoks = _word_tokens(aligner, ref_str)
        if unk not in wtoks:
            assert "".join(wtoks) == ref_str, (
                f"{name} phones: word tokens {''.join(wtoks)!r} vs reference {ref_str!r}"
            )
        pos += len(wtoks)
    assert pos == len(ours_p)

    if not with_aas:
        return None, None

    # timestamps: AAS via the package function, standard interval-dict format
    # (reference phones re-segmented to tokenizer symbols so both sides are
    # at the same granularity)
    ref_iv = {
        "words": [{"text": t, "start": s, "end": e} for s, e, t in ref_w],
        "phones": [{"text": t, "start": s, "end": e} for s, e, t in ref_tok],
    }
    our_iv = {
        "words": [{"text": o["text"], "start": o["start"], "end": o["end"]} for o in ours_w],
        "phones": [{"text": o["text"], "start": o["start"], "end": o["end"]} for o in ours_p],
    }
    aas = compute_aas(ref_iv, our_iv)
    return aas["word_aas_ms"], aas["phone_aas_ms"]


def _check_mean_aas(label, word_aass, phone_aass, compared, max_ms):
    mw = sum(word_aass) / len(word_aass) if word_aass else None
    mp = sum(phone_aass) / len(phone_aass) if phone_aass else None
    med_w = sorted(word_aass)[len(word_aass) // 2] if word_aass else None
    med_p = sorted(phone_aass)[len(phone_aass) // 2] if phone_aass else None
    print(f"\n{label}: compared {compared} items; mean word AAS "
          f"{mw:.1f} ms, mean phone AAS {mp:.1f} ms "
          f"(median word {med_w:.1f} ms, median phone {med_p:.1f} ms; "
          f"mean bound {max_ms} ms)")
    assert mw is not None and mw < max_ms, (
        f"{label}: mean word AAS {mw} ms not below {max_ms} ms"
    )
    assert mp is not None and mp < max_ms, (
        f"{label}: mean phone AAS {mp} ms not below {max_ms} ms"
    )


# --------------------------------------------------------------------------
# FLEURS de_de vs MFA TextGrids
# --------------------------------------------------------------------------

@pytest.mark.integration
@pytest.mark.slow
def test_aligner_matches_mfa_fleurs(fleurs_aligner):
    pytest.importorskip("datasets")
    from datasets import load_dataset

    ds = load_dataset(
        os.path.join(TEST_DATA_ROOT, "fleurs.py"),
        FLEURS_LANG,
        split="test",
        streaming=True,
        trust_remote_code=True,
    )
    n_items = _env_int("MFA_REF_ITEMS", "FAM_REF_ITEMS")

    compared = 0
    failures = []
    batch = []

    def run_batch(items):
        nonlocal compared
        keep, audios, texts, word_texts = [], [], [], []
        for x in items:
            wav = os.path.basename(x["audio"]["path"])
            stem = os.path.splitext(wav)[0]
            tg = os.path.join(MFA_TG_DIR, stem + ".TextGrid")
            if not os.path.exists(tg):
                continue
            tiers = parse_textgrid(tg)
            ref = build_reference(tiers["words"], tiers["phones"])
            audios.append(x["audio"]["array"])
            texts.append(ref["text"])
            word_texts.append(ref["word_text"])
            keep.append((wav, ref))
        if not keep:
            return
        results = fleurs_aligner.align_batch(
            audios, texts, word_texts=word_texts, batch_size=len(keep)
        )
        for (wav, ref), r in zip(keep, results):
            try:
                # sequences only - timestamps are not scored against MFA
                compare_against_reference(wav, r, ref, fleurs_aligner)
            except AssertionError as e:
                failures.append(str(e))
                continue
            compared += 1

    for it in ds:
        batch.append(it)
        if len(batch) < BATCH_SIZE:
            continue
        run_batch(batch)
        batch = []
        if n_items is not None and compared >= n_items:
            break
    if batch and (n_items is None or compared < n_items):
        run_batch(batch)

    assert compared >= 100, f"only {compared} FLEURS items had an MFA alignment"
    if failures:
        print(f"\n{len(failures)} items failed exact-sequence comparison:")
        for f in failures[:20]:
            print("  " + f)
    assert not failures, f"{len(failures)} items failed exact-sequence comparison"
    print(f"\nFLEURS de_de vs MFA: compared {compared} items; "
          f"all phone/word sequences match exactly (<unk> excused)")


# --------------------------------------------------------------------------
# DORECO anal1239 validation parquet
# --------------------------------------------------------------------------

@pytest.mark.integration
@pytest.mark.slow
def test_aligner_matches_doreco(doreco_aligner):
    pd = pytest.importorskip("pandas")

    df = pd.read_parquet(DORECO_PARQUET)
    n_items = _env_int("DORECO_REF_ITEMS")
    rows = list(df.iterrows())
    if n_items is not None:
        rows = rows[:n_items]

    compared = 0
    word_aass, phone_aass = [], []
    failures = []
    for i0 in range(0, len(rows), BATCH_SIZE):
        chunk = rows[i0 : i0 + BATCH_SIZE]
        audios, texts, word_texts, refs, names = [], [], [], [], []
        for idx, row in chunk:
            words = [(w["start"], w["end"], w["text"]) for w in row["words"]]
            phones = [(p["start"], p["end"], p["phone"]) for p in row["phones"]]
            ref = build_reference(words, phones)
            audios.append(row["audio"]["array"])
            texts.append(ref["text"])
            word_texts.append(ref["word_text"])
            refs.append(ref)
            names.append(f"doreco[{idx}]")
        if not audios:
            continue
        results = doreco_aligner.align_batch(
            audios, texts, word_texts=word_texts, batch_size=len(audios)
        )
        for name, ref, r in zip(names, refs, results):
            try:
                waas, paas = compare_against_reference(
                    name, r, ref, doreco_aligner, with_aas=True
                )
            except AssertionError as e:
                failures.append(str(e))
                continue
            if waas is not None:
                word_aass.append(waas)
            if paas is not None:
                phone_aass.append(paas)
            compared += 1

    assert compared >= 100, f"only {compared} DORECO items compared"
    if failures:
        print(f"\n{len(failures)} items failed exact-sequence comparison:")
        for f in failures[:20]:
            print("  " + f)
    assert not failures, f"{len(failures)} items failed exact-sequence comparison"
    _check_mean_aas(f"DORECO {DORECO_LANG}", word_aass, phone_aass, compared, DORECO_MEAN_AAS_MAX_MS)


